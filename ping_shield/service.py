"""Generate and install the systemd *user* service + 15-minute timer.

No root required: units go to ``~/.config/systemd/user`` and are managed with
``systemctl --user``. ExecStart points at the exact interpreter ping-shield is
installed in (system, venv or pipx), so the unit keeps working regardless of
how the package was installed.
"""

from __future__ import annotations

import getpass
import shutil
import subprocess
import sys
from pathlib import Path
from typing import List, Sequence

from . import __version__
from .config import atomic_write_text, config_home

UNIT_NAME = "ping-shield"
INTERVAL_MINUTES = 15


class ServiceError(RuntimeError):
    pass


def unit_dir() -> Path:
    return config_home() / "systemd" / "user"


def service_path() -> Path:
    return unit_dir() / f"{UNIT_NAME}.service"


def timer_path() -> Path:
    return unit_dir() / f"{UNIT_NAME}.timer"


def bot_path() -> Path:
    return unit_dir() / f"{UNIT_NAME}-bot.service"


def _quote(arg: str) -> str:
    """Quote one argument for a systemd ``ExecStart=`` line."""
    escaped = arg.replace("\\", "\\\\").replace('"', '\\"').replace("%", "%%").replace("$", "$$")
    return f'"{escaped}"'


def exec_start(command: str = "--run") -> str:
    python = sys.executable
    if not python or not Path(python).is_absolute():
        raise ServiceError("cannot determine the absolute path of the Python interpreter")
    return " ".join(_quote(a) for a in (python, "-m", "ping_shield", command))


def render_service() -> str:
    # No NoNewPrivileges=: `crontab -l` is setuid/setgid on most distros and
    # fails under it, which would silently disable the crontab check.
    return f"""\
# Generated by ping-shield {__version__} (`ping-shield --setup-service`).
# Re-run that command after upgrading Python or moving the installation.
[Unit]
Description=ping-shield security scan (SSH, persistence, IDE extensions, threat intel)
Documentation=https://pypi.org/project/ping-shield/

[Service]
Type=oneshot
ExecStart={exec_start()}
Environment=PYTHONUNBUFFERED=1
Nice=10
IOSchedulingClass=idle
TimeoutStartSec=10min
"""


def render_bot() -> str:
    return f"""\
# Generated by ping-shield {__version__} (`ping-shield --setup-service`).
[Unit]
Description=ping-shield Telegram bot (alert buttons and chat commands)
Documentation=https://pypi.org/project/ping-shield/
StartLimitIntervalSec=0

[Service]
Type=simple
ExecStart={exec_start("--bot")}
Environment=PYTHONUNBUFFERED=1
Restart=always
RestartSec=15
Nice=10

[Install]
WantedBy=default.target
"""


def render_timer(minutes: int = INTERVAL_MINUTES) -> str:
    return f"""\
# Generated by ping-shield {__version__} (`ping-shield --setup-service`).
[Unit]
Description=Run ping-shield every {minutes} minutes

[Timer]
OnStartupSec=2min
OnUnitActiveSec={minutes}min
AccuracySec=1min
RandomizedDelaySec=30s
Unit={UNIT_NAME}.service

[Install]
WantedBy=timers.target
"""


def _systemctl(*args: str, check: bool = True) -> subprocess.CompletedProcess:
    binary = shutil.which("systemctl")
    if not binary:
        raise ServiceError("systemctl not found: this command needs a systemd-based distribution")
    proc = subprocess.run([binary, "--user", *args], capture_output=True, text=True, check=False, timeout=60)
    if check and proc.returncode != 0:
        detail = (proc.stderr or proc.stdout).strip()
        hint = ""
        if "bus" in detail.lower() or "XDG_RUNTIME_DIR" in detail:
            hint = ("\nHint: run this from your own desktop/SSH login session (not via sudo/su), "
                    "so a systemd user manager is available.")
        raise ServiceError(f"systemctl --user {' '.join(args)} failed: {detail}{hint}")
    return proc


def _linger_enabled() -> bool:
    loginctl = shutil.which("loginctl")
    if not loginctl:
        return False
    proc = subprocess.run(
        [loginctl, "show-user", getpass.getuser(), "--property=Linger", "--value"],
        capture_output=True, text=True, check=False, timeout=15,
    )
    return proc.stdout.strip() == "yes"


def install_service(enable: bool = True) -> List[str]:
    """Write the units, reload systemd and enable the timer. Returns human-readable steps."""
    _systemctl("show-environment")  # fail early when no user manager is reachable
    steps = []
    unit_dir().mkdir(parents=True, exist_ok=True)
    atomic_write_text(service_path(), render_service(), mode=0o644)
    steps.append(f"wrote {service_path()}")
    atomic_write_text(timer_path(), render_timer(), mode=0o644)
    steps.append(f"wrote {timer_path()}")
    atomic_write_text(bot_path(), render_bot(), mode=0o644)
    steps.append(f"wrote {bot_path()}")
    _systemctl("daemon-reload")
    steps.append("reloaded the systemd user manager")
    if enable:
        _systemctl("enable", "--now", f"{UNIT_NAME}.timer")
        steps.append(f"enabled and started {UNIT_NAME}.timer (every {INTERVAL_MINUTES} min)")
        _systemctl("enable", f"{UNIT_NAME}-bot.service")
        _systemctl("restart", f"{UNIT_NAME}-bot.service")  # restart picks up upgraded code
        steps.append(f"enabled and started {UNIT_NAME}-bot.service (alert buttons and chat commands)")
    if not _linger_enabled():
        steps.append(
            "note: scans only run while you are logged in. To scan around the clock run:\n"
            "      sudo loginctl enable-linger $USER"
        )
    return steps


def remove_service() -> List[str]:
    steps = []
    _systemctl("disable", "--now", f"{UNIT_NAME}.timer", check=False)
    _systemctl("disable", "--now", f"{UNIT_NAME}-bot.service", check=False)
    _systemctl("stop", f"{UNIT_NAME}.service", check=False)
    for path in (timer_path(), service_path(), bot_path()):
        if path.exists():
            path.unlink()
            steps.append(f"removed {path}")
    _systemctl("daemon-reload", check=False)
    steps.append("reloaded the systemd user manager")
    return steps


def service_status() -> Sequence[str]:
    if not shutil.which("systemctl"):
        return ["systemd: not available"]
    enabled = _systemctl("is-enabled", f"{UNIT_NAME}.timer", check=False).stdout.strip() or "not installed"
    active = _systemctl("is-active", f"{UNIT_NAME}.timer", check=False).stdout.strip() or "unknown"
    bot = _systemctl("is-active", f"{UNIT_NAME}-bot.service", check=False).stdout.strip() or "unknown"
    lines = [f"timer: {enabled}, {active}", f"bot: {bot}"]
    timers = _systemctl("list-timers", f"{UNIT_NAME}.timer", "--no-pager", check=False).stdout.strip()
    if timers and active == "active":
        lines += ["  " + line for line in timers.splitlines()[:2]]
    if enabled in ("enabled", "linked"):
        last = _systemctl("show", f"{UNIT_NAME}.service", "--property=Result", "--value", check=False).stdout.strip()
        if last:
            lines.append(f"last run result: {last}")
    return lines


def bot_active() -> bool:
    """True when the interactive bot service is running (so callback buttons will be answered)."""
    if not shutil.which("systemctl"):
        return False
    try:
        return _systemctl("is-active", f"{UNIT_NAME}-bot.service", check=False).stdout.strip() == "active"
    except (ServiceError, subprocess.SubprocessError):
        return False
